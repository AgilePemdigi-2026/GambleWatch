#!/usr/bin/env python3
"""Generate supabase/seed_keywords.sql from data/keywords.json.

Run from the repo root after editing data/keywords.json:
    python scripts/export_keywords_sql.py

Paste the generated file into Supabase Dashboard -> SQL Editor. It is an
upsert on (term, language), so it is safe to run again.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "data" / "keywords.json"
TARGET = ROOT / "supabase" / "seed_keywords.sql"


def quote(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def text_array(items) -> str:
    if not items:
        return "'{}'::text[]"
    return "array[" + ", ".join(quote(str(i)) for i in items) + "]::text[]"


def row(k: dict) -> str:
    return "  ({term}, {category}, {weight}, {active}, {language}, {variations}, {aliases})".format(
        term=quote(k["term"]),
        category=quote(k.get("category") or "general"),
        weight=float(k.get("weight", 0.5)),
        active="true" if k.get("active", True) else "false",
        language=quote(k.get("language") or "id"),
        variations=text_array(k.get("variations")),
        aliases=text_array(k.get("aliases")),
    )


def main() -> int:
    keywords = json.loads(SOURCE.read_text(encoding="utf-8"))
    lines = [
        "-- Generated by scripts/export_keywords_sql.py from data/keywords.json",
        "-- Jalankan di Supabase Dashboard -> SQL Editor (aman dijalankan ulang).",
        "",
        "insert into public.keywords (term, category, weight, active, language, variations, aliases) values",
        ",\n".join(row(k) for k in keywords),
        "on conflict (term, language) do update set",
        "  category   = excluded.category,",
        "  weight     = excluded.weight,",
        "  active     = excluded.active,",
        "  variations = excluded.variations,",
        "  aliases    = excluded.aliases;",
        "",
    ]
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(keywords)} kata kunci ditulis ke {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
